pub const RELATIVE_PATH: &str = ".lorry/dependencies-v1.toml";
pub const TRANSACTION_RELATIVE_PATH: &str = ".lorry/transactions/dependency-upgrade-v1";

pub fn require_no_transaction(root: &Path) -> Result<()> {
    let path = root.join(TRANSACTION_RELATIVE_PATH);
    match fs::symlink_metadata(&path) {
        Ok(metadata) if metadata.file_type().is_symlink() || !metadata.is_dir() => {
            Err(Error::failure(format!(
                "unfinished Lorry dependency transaction path `{}` is not a real directory",
                path.display()
            )))
        }
        Ok(_) => Err(Error::failure(format!(
            "an unfinished Lorry dependency upgrade exists at `{}`",
            path.display()
        ))
        .with_help("rerun the identical `lorry vendor upgrade` command to complete it")),
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => Ok(()),
        Err(error) => Err(Error::failure(format!(
            "failed to inspect Lorry dependency transactions at `{}`: {error}",
            path.display()
        ))),
    }
}

#[derive(Clone, Debug, Eq, PartialEq)]
pub struct State {
    pub manifest_dependencies_sha256: String,
    pub cargo_lock_sha256: String,
    pub targets: Vec<String>,
    pub direct: Vec<DirectRegistryDependency>,
    pub locked: Vec<LockedRegistryPackage>,
    pub admitted: Vec<AdmittedRegistryPackage>,
}

#[derive(Clone, Debug, Eq, Ord, PartialEq, PartialOrd)]
pub struct LockedRegistryPackage {
    pub name: String,
    pub version: String,
    pub checksum: String,
}

#[derive(Clone, Debug, Eq, Ord, PartialEq, PartialOrd)]
pub struct DirectRegistryDependency {
    pub alias: String,
    pub package: String,
    pub requirement: String,
    pub target: Option<String>,
}

#[derive(Clone, Debug, Eq, Ord, PartialEq, PartialOrd)]
pub struct AdmittedRegistryPackage {
    pub name: String,
    pub version: String,
    pub checksum: String,
    pub license: String,
    pub source_tree_sha256: String,
    pub build_script: bool,
    pub native_tools: BTreeSet<NativeToolRole>,
}

impl State {
    pub fn path(root: &Path) -> PathBuf {
        root.join(RELATIVE_PATH)
    }

    pub fn render(&self) -> Result<Vec<u8>> {
        validate_sorted_unique(&self.targets, "target")?;
        validate_sorted_unique(&self.direct, "direct dependency")?;
        validate_sorted_unique(&self.locked, "locked package")?;
        validate_sorted_unique(&self.admitted, "admitted package")?;
        require_sha256(
            &self.manifest_dependencies_sha256,
            "manifest dependency fingerprint",
        )?;
        require_sha256(&self.cargo_lock_sha256, "Cargo.lock fingerprint")?;

        let mut output = String::new();
        output.push_str("# Generated by Lorry. Do not edit.\n");
        output.push_str("format-version = 1\n");
        output.push_str("source-tree-format-version = 1\n");
        output.push_str("manifest-dependencies-sha256 = ");
        write_toml_string(&mut output, &self.manifest_dependencies_sha256);
        output.push_str("\ncargo-lock-sha256 = ");
        write_toml_string(&mut output, &self.cargo_lock_sha256);
        output.push_str("\ntargets = [");
        for (index, target) in self.targets.iter().enumerate() {
            if index != 0 {
                output.push_str(", ");
            }
            write_toml_string(&mut output, target);
        }
        output.push_str("]\n");

        for dependency in &self.direct {
            output.push_str("\n[[direct-registry]]\nalias = ");
            write_toml_string(&mut output, &dependency.alias);
            output.push_str("\npackage = ");
            write_toml_string(&mut output, &dependency.package);
            output.push_str("\nrequirement = ");
            write_toml_string(&mut output, &dependency.requirement);
            if let Some(target) = &dependency.target {
                output.push_str("\ntarget = ");
                write_toml_string(&mut output, target);
            }
            output.push('\n');
        }

        for package in &self.locked {
            require_identity(&package.name, &package.version, &package.checksum)?;
            output.push_str("\n[[locked-registry]]\nname = ");
            write_toml_string(&mut output, &package.name);
            output.push_str("\nversion = ");
            write_toml_string(&mut output, &package.version);
            output.push_str("\nchecksum = ");
            write_toml_string(&mut output, &package.checksum);
            output.push('\n');
        }
        for package in &self.admitted {
            require_identity(&package.name, &package.version, &package.checksum)?;
            require_sha256(&package.source_tree_sha256, "source-tree digest")?;
            output.push_str("\n[[admitted-registry]]\nname = ");
            write_toml_string(&mut output, &package.name);
            output.push_str("\nversion = ");
            write_toml_string(&mut output, &package.version);
            output.push_str("\nchecksum = ");
            write_toml_string(&mut output, &package.checksum);
            output.push_str("\nlicense = ");
            write_toml_string(&mut output, &package.license);
            output.push_str("\nsource-tree-sha256 = ");
            write_toml_string(&mut output, &package.source_tree_sha256);
            output.push_str("\nbuild-script = ");
            output.push_str(if package.build_script {
                "true"
            } else {
                "false"
            });
            output.push_str("\nnative-tools = [");
            for (index, role) in package.native_tools.iter().enumerate() {
                if index != 0 {
                    output.push_str(", ");
                }
                write_toml_string(&mut output, native_tool_name(*role));
            }
            output.push_str("]\n");
        }
        Ok(output.into_bytes())
    }

    pub fn load(root: &Path) -> Result<Option<Self>> {
        let path = Self::path(root);
        if !path.is_file() {
            return Ok(None);
        }
        let document = Document::load(&path, "Lorry dependency state")?;
        require_keys(
            &path,
            document.root(),
            &[
                "format-version",
                "source-tree-format-version",
                "manifest-dependencies-sha256",
                "cargo-lock-sha256",
                "targets",
            ],
            &["direct-registry", "locked-registry", "admitted-registry"],
        )?;
        if required_item(&path, document.root(), "format-version")?.as_integer() != Some(1) {
            return Err(Error::failure(format!(
                "unsupported Lorry dependency state format in `{}`",
                path.display()
            )));
        }
        if required_item(&path, document.root(), "source-tree-format-version")?.as_integer()
            != Some(1)
        {
            return Err(Error::failure(format!(
                "unsupported source-tree format in Lorry dependency state `{}`",
                path.display()
            )));
        }
        let manifest_dependencies_sha256 =
            required_string(&path, document.root(), "manifest-dependencies-sha256")?;
        let cargo_lock_sha256 = required_string(&path, document.root(), "cargo-lock-sha256")?;
        let targets = required_strings(&path, document.root(), "targets")?;
        let direct = parse_direct(&path, &document)?;
        let locked = parse_locked(&path, &document)?;
        let admitted = parse_admitted(&path, &document)?;
        let state = Self {
            manifest_dependencies_sha256,
            cargo_lock_sha256,
            targets,
            direct,
            locked,
            admitted,
        };
        state.render()?;
        validate_package_identities(&state.locked, |package| (&package.name, &package.version))?;
        validate_package_identities(&state.admitted, |package| (&package.name, &package.version))?;
        Ok(Some(state))
    }

    pub fn validate_manifest(&self, manifest: &Manifest) -> Result<()> {
        let current_direct = direct_registry_dependencies(manifest);
        if self.direct != current_direct
            || self.manifest_dependencies_sha256 != manifest_dependencies_sha256(manifest)
        {
            return Err(manifest_mismatch(&self.direct, &current_direct));
        }
        let lock = manifest.lock.as_ref().ok_or_else(|| {
            Error::failure("dependency admission state exists, but Cargo.lock is missing")
                .with_help("restore Cargo.lock or run an explicit `lorry vendor upgrade`")
        })?;
        let current_locked = locked_registry_packages(lock)?;
        if self.locked != current_locked || self.cargo_lock_sha256 != cargo_lock_sha256(lock) {
            return Err(lock_mismatch(&self.locked, &current_locked));
        }
        Ok(())
    }

    pub fn require_target(&self, target: &str) -> Result<()> {
        if self
            .targets
            .binary_search_by(|value| value.as_str().cmp(target))
            .is_ok()
        {
            Ok(())
        } else {
            Err(Error::failure(format!(
                "Lorry dependency state does not admit target `{target}`"
            ))
            .with_help("run `lorry vendor` with this target in the configured vendor target set"))
        }
    }

    pub fn apply_to_policy(&self, policy: &mut Policy, root: &Path) -> Result<()> {
        for (index, package) in self.admitted.iter().enumerate() {
            let id = format!("lorry-state-{index:05}");
            if policy.rules.contains_key(&id) {
                return Err(Error::failure(format!(
                    "configured policy rule `{id}` conflicts with generated dependency state"
                )));
            }
            policy.rules.insert(
                id,
                PolicyRule {
                    action: PolicyAction::Allow,
                    name: Some(package.name.clone()),
                    version: Some(
                        semver::VersionReq::parse(&format!("={}", package.version)).map_err(
                            |error| {
                                Error::failure(format!(
                                    "dependency state has invalid exact version for `{} {}`: {error}",
                                    package.name, package.version
                                ))
                            },
                        )?,
                    ),
                    source: Some("crates.io".to_owned()),
                    checksum: Some(package.checksum.clone()),
                    source_tree_sha256: Some(package.source_tree_sha256.clone()),
                    license: Some(package.license.clone()),
                    allow_build_script: package.build_script,
                    native_tools: package.native_tools.clone(),
                    provenance: Self::path(root),
                },
            );
        }
        Ok(())
    }

    pub fn from_resolution(
        manifest: &Manifest,
        targets: impl IntoIterator<Item = String>,
        resolution: &Resolution,
        evidence: &std::collections::BTreeMap<PackageKey, PackageEvidence>,
        admission: &Admission,
    ) -> Result<Self> {
        let lock = manifest
            .lock
            .as_ref()
            .ok_or_else(|| Error::failure("cannot create dependency state without Cargo.lock"))?;
        let mut targets = targets.into_iter().collect::<Vec<_>>();
        targets.sort_unstable();
        targets.dedup();
        let mut admitted = Vec::new();
        for package in &resolution.packages {
            let ResolvedSource::CratesIo { checksum } = package.source else {
                continue;
            };
            let package_evidence = evidence.get(&package.key).ok_or_else(|| {
                Error::failure(format!(
                    "cannot create dependency state without evidence for `{} {}`",
                    package.key.name, package.key.version
                ))
            })?;
            let package_admission = admission.packages.get(&package.key).ok_or_else(|| {
                Error::failure(format!(
                    "cannot create dependency state without admission for `{} {}`",
                    package.key.name, package.key.version
                ))
            })?;
            admitted.push(AdmittedRegistryPackage {
                name: package.key.name.clone(),
                version: package.key.version.to_string(),
                checksum: hex(&checksum),
                license: package_evidence.license.clone(),
                source_tree_sha256: hex(&package_evidence.source_tree_sha256),
                build_script: package_evidence.build_script,
                native_tools: package_admission.native_tools.clone(),
            });
        }
        admitted.sort_unstable();
        Ok(Self {
            manifest_dependencies_sha256: manifest_dependencies_sha256(manifest),
            cargo_lock_sha256: cargo_lock_sha256(lock),
            targets,
            direct: direct_registry_dependencies(manifest),
            locked: locked_registry_packages(lock)?,
            admitted,
        })
    }

    pub fn write(&self, root: &Path) -> Result<()> {
        let directory = root.join(".lorry");
        match fs::symlink_metadata(&directory) {
            Ok(metadata) if metadata.file_type().is_symlink() || !metadata.is_dir() => {
                return Err(Error::failure(format!(
                    "Lorry state directory `{}` is not a real directory",
                    directory.display()
                )));
            }
            Ok(_) => {}
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => {
                fs::create_dir(&directory).map_err(|error| {
                    Error::failure(format!(
                        "failed to create Lorry state directory `{}`: {error}",
                        directory.display()
                    ))
                })?;
                #[cfg(unix)]
                fs::set_permissions(
                    &directory,
                    std::os::unix::fs::PermissionsExt::from_mode(0o700),
                )
                .map_err(|error| {
                    Error::failure(format!(
                        "failed to make Lorry state directory `{}` private: {error}",
                        directory.display()
                    ))
                })?;
            }
            Err(error) => {
                return Err(Error::failure(format!(
                    "failed to inspect Lorry state directory `{}`: {error}",
                    directory.display()
                )));
            }
        }
        let mut staged = AtomicFile::new(&Self::path(root))?;
        staged.write_all(&self.render()?)?;
        staged.commit()
    }
}

fn manifest_mismatch(
    previous: &[DirectRegistryDependency],
    current: &[DirectRegistryDependency],
) -> Error {
    let removed = previous
        .iter()
        .filter(|dependency| !current.contains(dependency))
        .collect::<Vec<_>>();
    let added = current
        .iter()
        .filter(|dependency| !previous.contains(dependency))
        .collect::<Vec<_>>();
    if let ([old], [new]) = (removed.as_slice(), added.as_slice())
        && old.alias == new.alias
        && old.package == new.package
        && old.target == new.target
    {
        let version = new
            .requirement
            .strip_prefix('=')
            .filter(|value| semver::Version::parse(value).is_ok())
            .unwrap_or("VERSION");
        return Error::failure(format!(
            "dependency admission state is stale: Cargo.toml changed `{}` from `{}` to `{}`",
            new.alias, old.requirement, new.requirement
        ))
        .with_help(format!(
            "review and adopt the change with `lorry vendor upgrade {} --to {version}`",
            new.alias,
        ));
    }
    Error::failure("dependency admission state is stale: Cargo.toml dependency semantics changed")
        .with_help(
            "review the dependency changes, then run `lorry vendor upgrade --from-cargo-lock`",
        )
}

fn lock_mismatch(previous: &[LockedRegistryPackage], current: &[LockedRegistryPackage]) -> Error {
    let removed = previous
        .iter()
        .filter(|package| !current.contains(package))
        .collect::<Vec<_>>();
    let added = current
        .iter()
        .filter(|package| !previous.contains(package))
        .collect::<Vec<_>>();
    if let ([old], [new]) = (removed.as_slice(), added.as_slice())
        && old.name == new.name
        && old.version != new.version
    {
        return Error::failure(format!(
            "dependency admission state is stale: Cargo.lock selects `{} {}`, but Lorry approved `{} {}`",
            new.name, new.version, old.name, old.version
        ))
        .with_help(format!(
            "review and adopt the change with `lorry vendor upgrade {} --to {}`",
            new.name, new.version
        ));
    }
    Error::failure(format!(
        "dependency admission state is stale: Cargo.lock changed ({} removed, {} added identities)",
        removed.len(),
        added.len()
    ))
    .with_help("review and adopt the Cargo graph with `lorry vendor upgrade --from-cargo-lock`")
}

fn parse_direct(path: &Path, document: &Document) -> Result<Vec<DirectRegistryDependency>> {
    let Some(item) = document.root().get("direct-registry") else {
        return Ok(Vec::new());
    };
    let tables = item.as_array_of_tables().ok_or_else(|| {
        Error::failure(format!(
            "`direct-registry` in `{}` must be an array of tables",
            path.display()
        ))
    })?;
    tables
        .iter()
        .map(|table| {
            require_keys(
                path,
                table,
                &["alias", "package", "requirement"],
                &["target"],
            )?;
            let requirement = required_string(path, table, "requirement")?;
            semver::VersionReq::parse(&requirement).map_err(|error| {
                Error::failure(format!(
                    "dependency state `{}` has invalid requirement `{requirement}`: {error}",
                    path.display()
                ))
            })?;
            Ok(DirectRegistryDependency {
                alias: required_string(path, table, "alias")?,
                package: required_string(path, table, "package")?,
                requirement,
                target: table
                    .get("target")
                    .map(|_| required_string(path, table, "target"))
                    .transpose()?,
            })
        })
        .collect()
}

fn parse_locked(path: &Path, document: &Document) -> Result<Vec<LockedRegistryPackage>> {
    let Some(item) = document.root().get("locked-registry") else {
        return Ok(Vec::new());
    };
    let tables = item.as_array_of_tables().ok_or_else(|| {
        Error::failure(format!(
            "`locked-registry` in `{}` must be an array of tables",
            path.display()
        ))
    })?;
    tables
        .iter()
        .map(|table| {
            require_keys(path, table, &["name", "version", "checksum"], &[])?;
            Ok(LockedRegistryPackage {
                name: required_string(path, table, "name")?,
                version: required_string(path, table, "version")?,
                checksum: required_string(path, table, "checksum")?,
            })
        })
        .collect()
}

fn parse_admitted(path: &Path, document: &Document) -> Result<Vec<AdmittedRegistryPackage>> {
    let Some(item) = document.root().get("admitted-registry") else {
        return Ok(Vec::new());
    };
    let tables = item.as_array_of_tables().ok_or_else(|| {
        Error::failure(format!(
            "`admitted-registry` in `{}` must be an array of tables",
            path.display()
        ))
    })?;
    tables
        .iter()
        .map(|table| {
            require_keys(
                path,
                table,
                &[
                    "name",
                    "version",
                    "checksum",
                    "license",
                    "source-tree-sha256",
                    "build-script",
                    "native-tools",
                ],
                &[],
            )?;
            let mut native_tools = BTreeSet::new();
            for role in required_strings(path, table, "native-tools")? {
                let role = match role.as_str() {
                    "c-compiler" => NativeToolRole::CCompiler,
                    "archiver" => NativeToolRole::Archiver,
                    _ => {
                        return Err(Error::failure(format!(
                            "dependency state `{}` has unsupported native-tool role `{role}`",
                            path.display()
                        )));
                    }
                };
                if !native_tools.insert(role) {
                    return Err(Error::failure(format!(
                        "dependency state `{}` repeats native-tool role `{}`",
                        path.display(),
                        native_tool_name(role)
                    )));
                }
            }
            Ok(AdmittedRegistryPackage {
                name: required_string(path, table, "name")?,
                version: required_string(path, table, "version")?,
                checksum: required_string(path, table, "checksum")?,
                license: required_string(path, table, "license")?,
                source_tree_sha256: required_string(path, table, "source-tree-sha256")?,
                build_script: required_item(path, table, "build-script")?
                    .as_bool()
                    .ok_or_else(|| {
                        Error::failure(format!(
                            "`build-script` in `{}` must be a boolean",
                            path.display()
                        ))
                    })?,
                native_tools,
            })
        })
        .collect()
}

fn require_keys(path: &Path, table: &Table, required: &[&str], optional: &[&str]) -> Result<()> {
    for key in required {
        if !table.contains_key(key) {
            return Err(Error::failure(format!(
                "dependency state `{}` is missing `{key}`",
                path.display()
            )));
        }
    }
    for (key, _) in table.iter() {
        if !required.contains(&key) && !optional.contains(&key) {
            return Err(Error::failure(format!(
                "dependency state `{}` contains unknown key `{key}`",
                path.display()
            )));
        }
    }
    Ok(())
}

fn required_item<'a>(path: &Path, table: &'a Table, key: &str) -> Result<&'a Item> {
    table.get(key).ok_or_else(|| {
        Error::failure(format!(
            "dependency state `{}` is missing `{key}`",
            path.display()
        ))
    })
}

fn required_string(path: &Path, table: &Table, key: &str) -> Result<String> {
    required_item(path, table, key)?
        .as_str()
        .map(str::to_owned)
        .ok_or_else(|| {
            Error::failure(format!(
                "`{key}` in dependency state `{}` must be a string",
                path.display()
            ))
        })
}

fn required_strings(path: &Path, table: &Table, key: &str) -> Result<Vec<String>> {
    let array = required_item(path, table, key)?.as_array().ok_or_else(|| {
        Error::failure(format!(
            "`{key}` in dependency state `{}` must be an array",
            path.display()
        ))
    })?;
    array
        .iter()
        .map(|value| {
            value.as_str().map(str::to_owned).ok_or_else(|| {
                Error::failure(format!(
                    "`{key}` in dependency state `{}` must contain only strings",
                    path.display()
                ))
            })
        })
        .collect()
}

pub fn manifest_dependencies_sha256(manifest: &Manifest) -> String {
    let mut fields = Vec::new();
    for dependency in &manifest.dependencies {
        if dependency.source != DependencySource::CratesIo {
            continue;
        }
        let kind = match dependency.kind {
            DependencyKind::Normal => "normal",
            DependencyKind::Build => "build",
            DependencyKind::Dev => "development",
        };
        fields.push(format!(
            "dependency\0{}\0{}\0{}\0{}\0{}\0{}\0{}\0{}",
            dependency.alias,
            dependency.package,
            dependency.requirement,
            dependency.target.as_deref().unwrap_or(""),
            kind,
            dependency.optional,
            dependency.default_features,
            dependency.features.join("\0")
        ));
    }
    for (name, values) in &manifest.features {
        fields.push(format!("feature\0{name}\0{}", values.join("\0")));
    }
    for patch in &manifest.patches {
        fields.push(format!("patch\0{}\0{}", patch.alias, patch.package));
    }
    digest_fields(fields)
}

pub fn direct_registry_dependencies(manifest: &Manifest) -> Vec<DirectRegistryDependency> {
    let mut dependencies = manifest
        .dependencies
        .iter()
        .filter(|dependency| dependency.source == DependencySource::CratesIo)
        .map(|dependency| DirectRegistryDependency {
            alias: dependency.alias.clone(),
            package: dependency.package.clone(),
            requirement: dependency.requirement.to_string(),
            target: dependency.target.clone(),
        })
        .collect::<Vec<_>>();
    dependencies.sort_unstable();
    dependencies
}

pub fn cargo_lock_sha256(lock: &Lockfile) -> String {
    let mut fields = Vec::new();
    for package in &lock.packages {
        if package.source.as_deref()
            != Some("registry+https://github.com/rust-lang/crates.io-index")
        {
            continue;
        }
        let mut dependencies = package.dependencies.clone();
        dependencies.sort_unstable();
        fields.push(format!(
            "package\0{}\0{}\0{}\0{}",
            package.name,
            package.version.original,
            package.checksum.as_deref().unwrap_or(""),
            dependencies.join("\0")
        ));
    }
    digest_fields(fields)
}

pub fn locked_registry_packages(lock: &Lockfile) -> Result<Vec<LockedRegistryPackage>> {
    let mut packages = lock
        .packages
        .iter()
        .filter(|package| {
            package.source.as_deref()
                == Some("registry+https://github.com/rust-lang/crates.io-index")
        })
        .map(|package| {
            let checksum = package.checksum.clone().ok_or_else(|| {
                Error::failure(format!(
                    "locked crates.io package `{} {}` has no checksum",
                    package.name, package.version.original
                ))
            })?;
            Ok(LockedRegistryPackage {
                name: package.name.clone(),
                version: package.version.original.clone(),
                checksum,
            })
        })
        .collect::<Result<Vec<_>>>()?;
    packages.sort_unstable();
    validate_sorted_unique(&packages, "locked package")?;
    Ok(packages)
}

fn digest_fields(mut fields: Vec<String>) -> String {
    fields.sort_unstable();
    let mut hasher = Sha256::new();
    hasher.update(b"lorry-dependency-state-v1\0");
    hasher.update(&(fields.len() as u64).to_be_bytes());
    for field in fields {
        hasher.update(&(field.len() as u64).to_be_bytes());
        hasher.update(field.as_bytes());
    }
    hex(&hasher.finish())
}

fn validate_sorted_unique<T: Ord>(values: &[T], description: &str) -> Result<()> {
    if values.windows(2).any(|pair| pair[0] >= pair[1]) {
        return Err(Error::failure(format!(
            "dependency state {description} entries are not sorted and unique"
        )));
    }
    Ok(())
}

fn validate_package_identities<T>(
    packages: &[T],
    identity: impl Fn(&T) -> (&String, &String),
) -> Result<()> {
    let mut identities = BTreeSet::new();
    for package in packages {
        let (name, version) = identity(package);
        if !identities.insert((name, version)) {
            return Err(Error::failure(format!(
                "dependency state repeats package identity `{name} {version}`"
            )));
        }
    }
    Ok(())
}

fn require_identity(name: &str, version: &str, checksum: &str) -> Result<()> {
    if name.is_empty() || version.is_empty() {
        return Err(Error::failure(
            "dependency state contains an empty package identity",
        ));
    }
    semver::Version::parse(version).map_err(|error| {
        Error::failure(format!(
            "dependency state package `{name}` has invalid version `{version}`: {error}"
        ))
    })?;
    require_sha256(checksum, "package checksum")
}

fn require_sha256(value: &str, description: &str) -> Result<()> {
    if value.len() == 64
        && value
            .bytes()
            .all(|byte| byte.is_ascii_digit() || (b'a'..=b'f').contains(&byte))
    {
        Ok(())
    } else {
        Err(Error::failure(format!(
            "dependency state {description} is not a lowercase SHA-256"
        )))
    }
}

fn native_tool_name(role: NativeToolRole) -> &'static str {
    match role {
        NativeToolRole::CCompiler => "c-compiler",
        NativeToolRole::Archiver => "archiver",
    }
}

