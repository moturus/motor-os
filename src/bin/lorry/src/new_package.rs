use std::fs;
use std::path::{Path, PathBuf};

use crate::atomic::AtomicDirectory;
use crate::diagnostic::{Error, Result};

const MANIFEST: &str =
    "[package]\nname = \"{name}\"\nversion = \"0.1.0\"\nedition = \"2024\"\n\n[dependencies]\n";
const LOCKFILE: &str = "# This file is automatically @generated by Cargo.\n\
# It is not intended for manual editing.\n\
version = 4\n\
\n\
[[package]]\n\
name = \"{name}\"\n\
version = \"0.1.0\"\n";
const MAIN_SOURCE: &str = "fn main() {\n    println!(\"Hello, world!\");\n}\n";

pub fn execute(path: &str, quiet: bool) -> Result<i32> {
    let requested_destination = Path::new(path);
    let name = package_name(requested_destination)?;
    let destination = normalized_destination(requested_destination, name);
    let parent = destination
        .parent()
        .expect("normalized package destinations always have a parent");

    let staging = AtomicDirectory::new(parent, name)?;
    let source_directory = staging.path().join("src");
    fs::create_dir(&source_directory).map_err(|error| {
        Error::failure(format!(
            "failed to create package source directory `{}`: {error}",
            source_directory.display()
        ))
    })?;
    write(
        &staging.path().join("Cargo.toml"),
        &MANIFEST.replace("{name}", name),
    )?;
    write(
        &staging.path().join("Cargo.lock"),
        &LOCKFILE.replace("{name}", name),
    )?;
    write(&source_directory.join("main.rs"), MAIN_SOURCE)?;

    if !staging.commit_no_replace(&destination)? {
        return Err(Error::failure(format!(
            "package destination `{}` already exists",
            requested_destination.display()
        ))
        .with_help("choose a path that does not already exist"));
    }
    if !quiet {
        eprintln!("    Created binary (application) `{name}` package");
    }
    Ok(0)
}

fn normalized_destination(path: &Path, name: &str) -> PathBuf {
    path.parent()
        .filter(|parent| !parent.as_os_str().is_empty())
        .unwrap_or_else(|| Path::new("."))
        .join(name)
}

fn write(path: &Path, contents: &str) -> Result<()> {
    fs::write(path, contents).map_err(|error| {
        Error::failure(format!(
            "failed to write package file `{}`: {error}",
            path.display()
        ))
    })
}

fn package_name(path: &Path) -> Result<&str> {
    let name = path
        .file_name()
        .and_then(|name| name.to_str())
        .ok_or_else(|| {
            Error::failure(format!(
                "package path `{}` does not end in a UTF-8 name",
                path.display()
            ))
            .with_help("use a path ending in a valid Rust package name")
        })?;
    let valid = name.len() <= 64
        && name
            .bytes()
            .next()
            .is_some_and(|byte| byte.is_ascii_alphabetic() || byte == b'_')
        && name
            .bytes()
            .all(|byte| byte.is_ascii_alphanumeric() || matches!(byte, b'-' | b'_'))
        && name.bytes().any(|byte| byte.is_ascii_alphabetic())
        && !is_rust_keyword(name)
        && name != "test";
    if !valid {
        return Err(Error::failure(format!(
            "package path `{}` ends in invalid package name `{name}`",
            path.display()
        ))
        .with_help(
            "use 1–64 ASCII letters, digits, `-`, or `_`; start with a letter or `_`, include a letter, and avoid Rust keywords",
        ));
    }
    Ok(name)
}

fn is_rust_keyword(name: &str) -> bool {
    matches!(
        name,
        "Self"
            | "abstract"
            | "as"
            | "async"
            | "await"
            | "become"
            | "box"
            | "break"
            | "const"
            | "continue"
            | "crate"
            | "do"
            | "dyn"
            | "else"
            | "enum"
            | "extern"
            | "false"
            | "final"
            | "fn"
            | "for"
            | "gen"
            | "if"
            | "impl"
            | "in"
            | "let"
            | "loop"
            | "macro"
            | "match"
            | "mod"
            | "move"
            | "mut"
            | "override"
            | "priv"
            | "pub"
            | "ref"
            | "return"
            | "self"
            | "static"
            | "struct"
            | "super"
            | "trait"
            | "true"
            | "try"
            | "type"
            | "typeof"
            | "unsafe"
            | "unsized"
            | "use"
            | "virtual"
            | "where"
            | "while"
            | "yield"
    )
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::path::PathBuf;
    use std::sync::atomic::{AtomicU64, Ordering};

    static NEXT: AtomicU64 = AtomicU64::new(0);

    struct TempDirectory(PathBuf);

    impl TempDirectory {
        fn new() -> Self {
            let path = std::env::temp_dir().join(format!(
                "lorry-new-test-{}-{}",
                std::process::id(),
                NEXT.fetch_add(1, Ordering::Relaxed)
            ));
            let _ = fs::remove_dir_all(&path);
            fs::create_dir(&path).unwrap();
            Self(path)
        }
    }

    impl Drop for TempDirectory {
        fn drop(&mut self) {
            let _ = fs::remove_dir_all(&self.0);
        }
    }

    #[test]
    fn creates_default_binary_package() {
        let temp = TempDirectory::new();
        let destination = temp.0.join("example-app");

        execute(destination.to_str().unwrap(), true).unwrap();

        assert_eq!(
            fs::read_to_string(destination.join("Cargo.toml")).unwrap(),
            MANIFEST.replace("{name}", "example-app")
        );
        assert_eq!(
            fs::read_to_string(destination.join("src/main.rs")).unwrap(),
            MAIN_SOURCE
        );
        assert_eq!(
            fs::read_to_string(destination.join("Cargo.lock")).unwrap(),
            LOCKFILE.replace("{name}", "example-app")
        );
        assert!(!destination.join(".git").exists());
    }

    #[test]
    fn refuses_existing_destination_without_changing_it() {
        let temp = TempDirectory::new();
        let destination = temp.0.join("existing");
        fs::create_dir(&destination).unwrap();
        fs::write(destination.join("keep"), "unchanged").unwrap();

        let error = execute(destination.to_str().unwrap(), true).unwrap_err();

        assert!(error.render().contains("already exists"));
        assert_eq!(
            fs::read_to_string(destination.join("keep")).unwrap(),
            "unchanged"
        );
    }

    #[test]
    fn rejects_names_that_lorry_cannot_build() {
        for path in ["123-app", "match", "test", "non.ascii", "_"] {
            assert!(package_name(Path::new(path)).is_err(), "accepted {path}");
        }
        for path in ["app", "example-app", "_private"] {
            assert_eq!(package_name(Path::new(path)).unwrap(), path);
        }
    }

    #[test]
    fn normalizes_a_bare_relative_destination_for_atomic_publication() {
        let destination = normalized_destination(Path::new("hello"), "hello");

        assert_eq!(destination, Path::new("./hello"));
        assert_eq!(destination.parent(), Some(Path::new(".")));
    }
}
