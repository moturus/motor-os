#![allow(dead_code)]

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;

use semver::Version;

use crate::diagnostic::{Error, Result};
use crate::hash::hex;
use crate::manifest::{GitSelector, SourceWorkspace};
use crate::resolver::{PackageKey, PackageSourceKey, Resolution, ResolvedEdge, ResolvedSource};

const CRATES_IO_SOURCE: &str = "registry+https://github.com/rust-lang/crates.io-index";

#[derive(Clone, Debug, Eq, Ord, PartialEq, PartialOrd)]
struct Identity {
    name: String,
    version: Version,
    source: Option<String>,
}

struct Node {
    identity: Identity,
    checksum: Option<[u8; 32]>,
    dependencies: BTreeSet<Identity>,
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub(crate) enum Format {
    V1 = 1,
    V2,
    V3,
    V4,
}

impl Format {
    pub(crate) fn for_workspace(workspace: &SourceWorkspace) -> Result<Self> {
        let minimum = workspace
            .packages
            .iter()
            .filter(|member| !member.metadata.rust_version.is_empty())
            .map(|member| {
                crate::resolver::parse_local_rust_version(
                    &member.name,
                    &member.metadata.rust_version,
                )
                .map(|rust| rust.version)
            })
            .collect::<Result<Vec<_>>>()?
            .into_iter()
            .min();
        Ok(match minimum {
            None => Self::V4,
            Some(rust) if rust >= Version::new(1, 83, 0) => Self::V4,
            Some(rust) if rust >= Version::new(1, 53, 0) => Self::V3,
            Some(rust) if rust >= Version::new(1, 41, 0) => Self::V2,
            Some(_) => Self::V1,
        })
    }
}

/// Every member is already an ordinary node in a complete workspace graph.
pub(crate) fn render_workspace(resolution: &Resolution, format: Format) -> Result<Vec<u8>> {
    render_nodes(&resolved_nodes(resolution)?, format)
}

fn resolved_nodes(resolution: &Resolution) -> Result<BTreeMap<Identity, Node>> {
    let mut identities = BTreeMap::new();
    for package in &resolution.packages {
        let identity = identity(package.key.clone());
        if identities
            .insert(package.key.clone(), identity.clone())
            .is_some()
        {
            return Err(Error::failure(format!(
                "resolved graph repeats package `{} {}`",
                package.key.name, package.key.version
            )));
        }
    }

    let mut nodes = BTreeMap::new();
    for package in &resolution.packages {
        let identity = identities[&package.key].clone();
        let checksum = match (&package.key.source, &package.source) {
            (PackageSourceKey::CratesIo, ResolvedSource::CratesIo { checksum }) => Some(*checksum),
            (PackageSourceKey::Git(key_source), ResolvedSource::Git { cargo_source, .. })
                if key_source == cargo_source =>
            {
                None
            }
            (PackageSourceKey::Path(key_root), ResolvedSource::Path { logical_root, .. })
                if key_root == logical_root =>
            {
                None
            }
            _ => {
                return Err(Error::failure(format!(
                    "resolved package `{} {}` has inconsistent source identity",
                    package.key.name, package.key.version
                )));
            }
        };
        insert_node(
            &mut nodes,
            Node {
                identity,
                checksum,
                dependencies: edge_identities(&package.lock_edges, &identities)?,
            },
        )?;
    }
    Ok(nodes)
}

fn render_nodes(nodes: &BTreeMap<Identity, Node>, format: Format) -> Result<Vec<u8>> {
    let identities = nodes.keys().cloned().collect::<Vec<_>>();
    let mut output = String::from(
        "# This file is automatically @generated by Cargo.\n\
         # It is not intended for manual editing.\n",
    );
    if matches!(format, Format::V3 | Format::V4) {
        write!(output, "version = {}\n\n", format as u8).unwrap();
    }
    for node in nodes.values() {
        output.push_str("[[package]]\nname = ");
        write_toml_string(&mut output, &node.identity.name);
        output.push_str("\nversion = ");
        write_toml_string(&mut output, &node.identity.version.to_string());
        if let Some(source) = &node.identity.source {
            output.push_str("\nsource = ");
            write_toml_string(&mut output, &encode_source(source, format, true)?);
            if let Some(checksum) = node.checksum
                && format != Format::V1
            {
                output.push_str("\nchecksum = ");
                write_toml_string(&mut output, &hex(&checksum));
            }
        }
        if !node.dependencies.is_empty() {
            output.push_str("\ndependencies = [\n");
            let mut references = node
                .dependencies
                .iter()
                .map(|dependency| dependency_reference(dependency, &identities, format))
                .collect::<Result<Vec<_>>>()?;
            references.sort_unstable();
            for reference in references {
                output.push(' ');
                write_toml_string(&mut output, &reference);
                output.push_str(",\n");
            }
            output.push(']');
        }
        output.push_str("\n\n");
    }
    if format == Format::V1 {
        let mut checksums = BTreeMap::new();
        for node in nodes.values().filter(|node| node.identity.source.is_some()) {
            checksums.insert(
                format!(
                    "checksum {}",
                    dependency_reference(&node.identity, &identities, format)?
                ),
                node.checksum
                    .map(|checksum| hex(&checksum))
                    .unwrap_or_else(|| "<none>".to_owned()),
            );
        }
        if !checksums.is_empty() {
            output.push_str("[metadata]\n");
            for (key, value) in checksums {
                write_toml_string(&mut output, &key);
                output.push_str(" = ");
                write_toml_string(&mut output, &value);
                output.push('\n');
            }
        }
    } else {
        while output.ends_with("\n\n") {
            output.pop();
        }
    }
    Ok(output.into_bytes())
}

fn identity(key: PackageKey) -> Identity {
    Identity {
        name: key.name,
        version: key.version,
        source: match key.source {
            PackageSourceKey::CratesIo => Some(CRATES_IO_SOURCE.to_owned()),
            PackageSourceKey::Git(source) => Some(source),
            PackageSourceKey::Path(_) => None,
        },
    }
}

fn insert_node(nodes: &mut BTreeMap<Identity, Node>, node: Node) -> Result<()> {
    if nodes.contains_key(&node.identity) {
        return Err(Error::failure(format!(
            "Cargo.lock cannot distinguish multiple {} packages named `{} {}`",
            node.identity.source.as_deref().unwrap_or("path"),
            node.identity.name,
            node.identity.version
        )));
    }
    nodes.insert(node.identity.clone(), node);
    Ok(())
}

fn edge_identities(
    edges: &[ResolvedEdge],
    identities: &BTreeMap<PackageKey, Identity>,
) -> Result<BTreeSet<Identity>> {
    edges
        .iter()
        .map(|edge| {
            identities.get(&edge.package).cloned().ok_or_else(|| {
                Error::failure(format!(
                    "resolved lock edge names absent package `{} {}`",
                    edge.package.name, edge.package.version
                ))
            })
        })
        .collect()
}

fn dependency_reference(
    dependency: &Identity,
    identities: &[Identity],
    format: Format,
) -> Result<String> {
    if format == Format::V1 {
        return Ok(match &dependency.source {
            Some(source) => format!(
                "{} {} ({})",
                dependency.name,
                dependency.version,
                encode_source(source, format, false)?
            ),
            None => format!("{} {}", dependency.name, dependency.version),
        });
    }
    let same_name = identities
        .iter()
        .filter(|candidate| candidate.name == dependency.name)
        .collect::<Vec<_>>();
    if same_name.len() == 1 {
        return Ok(dependency.name.clone());
    }
    let base = format!("{} {}", dependency.name, dependency.version);
    let same_version = same_name
        .iter()
        .filter(|candidate| candidate.version == dependency.version)
        .count();
    if same_version == 1 || dependency.source.is_none() {
        Ok(base)
    } else {
        Ok(format!(
            "{base} ({})",
            encode_source(
                dependency
                    .source
                    .as_deref()
                    .expect("sourced dependency has an identity"),
                format,
                false
            )?
        ))
    }
}

pub(crate) fn encode_source(source: &str, format: Format, precise: bool) -> Result<String> {
    if source == CRATES_IO_SOURCE {
        return Ok(source.to_owned());
    }
    let locked = crate::git::parse_locked_source(source)?;
    let mut encoded = if format == Format::V4 {
        source.rsplit_once('#').unwrap().0.to_owned()
    } else {
        let query = match locked.selector {
            GitSelector::Head => String::new(),
            GitSelector::Branch(branch)
                if branch == "master" && !precise && matches!(format, Format::V1 | Format::V2) =>
            {
                String::new()
            }
            GitSelector::Branch(branch) => format!("?branch={branch}"),
            GitSelector::Tag(tag) => format!("?tag={tag}"),
            GitSelector::Revision(revision) => format!("?rev={revision}"),
        };
        format!("git+{}{query}", locked.url)
    };
    if precise {
        encoded.push('#');
        encoded.push_str(&locked.commit);
    }
    Ok(encoded)
}

pub(crate) fn write_toml_string(output: &mut String, value: &str) {
    output.push('"');
    for character in value.chars() {
        match character {
            '"' => output.push_str("\\\""),
            '\\' => output.push_str("\\\\"),
            '\n' => output.push_str("\\n"),
            '\r' => output.push_str("\\r"),
            '\t' => output.push_str("\\t"),
            character if character.is_control() => {
                let value = character as u32;
                if value <= 0xffff {
                    write!(output, "\\u{value:04X}").unwrap();
                } else {
                    write!(output, "\\U{value:08X}").unwrap();
                }
            }
            character => output.push(character),
        }
    }
    output.push('"');
}

