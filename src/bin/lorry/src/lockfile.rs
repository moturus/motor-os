    #[test]
    fn complete_workspace_lock_matches_cargo_with_optional_and_development_edges() {
        let fixture = Fixture::new();
        fs::write(fixture.0.join("Cargo.toml"), "[workspace]\nmembers = [\"a\", \"b\", \"c\"]\ndefault-members = [\"a\"]\nresolver = \"2\"\n").unwrap();
        for (name, dependencies) in [
            (
                "a",
                "[dependencies]\nb = { path = \"../b\", optional = true }\n[features]\nextra = [\"dep:b\"]\n[dev-dependencies]\nc = { path = \"../c\" }\n",
            ),
            (
                "b",
                "[target.'cfg(windows)'.dependencies]\nc = { path = \"../c\" }\n",
            ),
            ("c", "[dev-dependencies]\na = { path = \"../a\" }\n"),
        ] {
            let root = fixture.0.join(name);
            fs::create_dir_all(root.join("src")).unwrap();
            fs::write(root.join("src/lib.rs"), "").unwrap();
            fs::write(root.join("Cargo.toml"), format!("[package]\nname = \"{name}\"\nversion = \"0.1.0\"\nedition = \"2021\"\n{dependencies}")).unwrap();
        }
        let workspace = crate::manifest::SourceWorkspace::load(&fixture.0, None).unwrap();
        let resolution = crate::resolver::workspace::resolve_complete_workspace(
            &workspace,
            &mut crate::resolver::Catalog::default(),
            &crate::resolver::Options {
                resolver: crate::manifest::Resolver::V2,
                incompatible_rust_versions: None,
                rust_versions: vec![Version::new(1, 99, 0)],
                package_limit: crate::policy::PackageLimit::with_max(1),
                max_depth: Some(16),
            },
            &[],
            &mut |_, _, _| Ok(()),
        )
        .unwrap();
        let output = std::process::Command::new(env!("CARGO"))
            .args(["generate-lockfile", "--offline", "--manifest-path"])
            .arg(fixture.0.join("Cargo.toml"))
            .output()
            .unwrap();
        assert!(
            output.status.success(),
            "{}",
            String::from_utf8_lossy(&output.stderr)
        );
        assert_eq!(
            render_workspace(&resolution, Format::for_workspace(&workspace).unwrap()).unwrap(),
            fs::read(fixture.0.join("Cargo.lock")).unwrap()
        );
        let lock = crate::manifest::Lockfile::load(&fixture.0.join("Cargo.lock")).unwrap();
        crate::offline::validate_workspace_resolution(&lock, &resolution).unwrap();
        let original = fs::read(fixture.0.join("Cargo.lock")).unwrap();
        let mut stale = lock.clone();
        stale
            .packages
            .iter_mut()
            .find(|package| package.name == "a")
            .unwrap()
            .dependencies
            .clear();
        assert!(
            crate::offline::validate_workspace_resolution(&stale, &resolution)
                .unwrap_err()
                .to_string()
                .contains("dependency edges disagree")
        );
        let mut missing = lock.clone();
        missing.packages.retain(|package| package.name != "b");
        assert!(crate::offline::validate_workspace_resolution(&missing, &resolution).is_err());
        assert_eq!(fs::read(fixture.0.join("Cargo.lock")).unwrap(), original);
        let source = fs::read_to_string(fixture.0.join("a/Cargo.toml")).unwrap();
        for (rust, format) in [
            ("1.83", Format::V4),
            ("1.82", Format::V3),
            ("1.53", Format::V3),
            ("1.52", Format::V2),
            ("1.41", Format::V2),
            ("1.40", Format::V1),
        ] {
            fs::write(
                fixture.0.join("a/Cargo.toml"),
                source.replace(
                    "edition = \"2021\"",
                    &format!("edition = \"2015\"\nrust-version = \"{rust}\""),
                ),
            )
            .unwrap();
            fs::remove_file(fixture.0.join("Cargo.lock")).unwrap();
            let workspace = crate::manifest::SourceWorkspace::load(&fixture.0, None).unwrap();
            assert_eq!(Format::for_workspace(&workspace).unwrap(), format);
            let output = std::process::Command::new(env!("CARGO"))
                .args(["generate-lockfile", "--offline", "--manifest-path"])
                .arg(fixture.0.join("Cargo.toml"))
                .output()
                .unwrap();
            assert!(
                output.status.success(),
                "{}",
                String::from_utf8_lossy(&output.stderr)
            );
            assert_eq!(
                render_workspace(&resolution, format).unwrap(),
                fs::read(fixture.0.join("Cargo.lock")).unwrap(),
                "rust-version {rust}"
            );
            let lock = crate::manifest::Lockfile::load(&fixture.0.join("Cargo.lock")).unwrap();
            assert_eq!(lock.packages.len(), 3);
            crate::offline::validate_workspace_resolution(&lock, &resolution).unwrap();
        }
    }

    #[test]
    fn legacy_lock_checksums_and_git_dependency_sources_follow_cargo_encoding() {
        let registry = Identity {
            name: "registry".to_owned(),
            version: Version::new(1, 0, 0),
            source: Some(CRATES_IO_SOURCE.to_owned()),
        };
        let git = Identity {
            name: "git".to_owned(),
            version: Version::new(1, 0, 0),
            source: Some(format!(
                "git+https://example.com/repo?branch=feature%2Fmotor#{}",
                "0".repeat(40)
            )),
        };
        let nodes = BTreeMap::from([
            (
                registry.clone(),
                Node {
                    identity: registry.clone(),
                    checksum: Some([9; 32]),
                    dependencies: BTreeSet::new(),
                },
            ),
            (
                git.clone(),
                Node {
                    identity: git.clone(),
                    checksum: None,
                    dependencies: BTreeSet::new(),
                },
            ),
        ]);
        let legacy = String::from_utf8(render_nodes(&nodes, Format::V1).unwrap()).unwrap();
        assert!(!legacy.contains("\nchecksum ="));
        assert!(legacy.contains(&format!(
            "\"checksum registry 1.0.0 ({CRATES_IO_SOURCE})\" = \"{}\"",
            hex(&[9; 32])
        )));
        assert!(legacy.contains("\"checksum git 1.0.0 (git+https://example.com/repo?branch=feature/motor)\" = \"<none>\""));
        let fixture = Fixture::new();
        for format in [Format::V1, Format::V2, Format::V3, Format::V4] {
            fs::write(
                fixture.0.join("Cargo.lock"),
                render_nodes(&nodes, format).unwrap(),
            )
            .unwrap();
            let loaded = crate::manifest::Lockfile::load(&fixture.0.join("Cargo.lock")).unwrap();
            assert_eq!(loaded.format, format);
            assert_eq!(
                loaded
                    .packages
                    .iter()
                    .find(|package| package.name == "registry")
                    .unwrap()
                    .checksum,
                Some(hex(&[9; 32]))
            );
        }
        let duplicate = Identity {
            source: Some(CRATES_IO_SOURCE.to_owned()),
            ..git.clone()
        };
        let identities = [git.clone(), duplicate];
        assert_eq!(
            dependency_reference(&git, &identities, Format::V4).unwrap(),
            "git 1.0.0 (git+https://example.com/repo?branch=feature%2Fmotor)"
        );
        assert_eq!(
            dependency_reference(&git, &identities, Format::V3).unwrap(),
            "git 1.0.0 (git+https://example.com/repo?branch=feature/motor)"
        );
    }

    fn path_package(name: &str, version: &str, root: &Path) -> ResolvedPackage {
        let key = PackageKey {
            name: name.to_owned(),
            version: Version::parse(version).unwrap(),
            source: PackageSourceKey::Path(root.to_owned()),
        };
        package(
            key,
            ResolvedSource::Path {
                logical_root: root.to_owned(),
                physical_root: root.to_owned(),
                source_tree_sha256: [7; 32],
                patched_crates_io: false,
            },
        )
    }

    fn lock_edge(package: PackageKey) -> ResolvedEdge {
        ResolvedEdge {
            dependency_index: 0,
            alias: package.name.clone(),
            target: None,
            kind: crate::sparse::DependencyKind::Normal,
            parent_compile_kind: Some(crate::resolver::CompileKind::Target),
            compile_kind: crate::resolver::CompileKind::Target,
            context: FeatureContext::Target(String::new()),
            package,
        }
    }

    #[test]
    fn renders_a_crates_io_patch_with_its_git_identity() {
        let fixture = Fixture::new();
        let cargo_source = "git+https://example.com/demo.git?branch=motor#0123456789abcdef0123456789abcdef01234567";
        let key = PackageKey {
            name: "demo".to_owned(),
            version: Version::parse("1.2.3").unwrap(),
            source: PackageSourceKey::Git(cargo_source.to_owned()),
        };
        let mut root = path_package("root", "0.1.0", &fixture.0);
        root.lock_edges.push(lock_edge(key.clone()));
        let resolution = Resolution {
            root_edges: Vec::new(),
            packages: vec![
                root,
                package(
                    key,
                    ResolvedSource::Git {
                        cargo_source: cargo_source.to_owned(),
                        git_url: "https://example.com/demo.git".to_owned(),
                        requested_revision: "motor".to_owned(),
                        resolved_commit: "0123456789abcdef0123456789abcdef01234567".to_owned(),
                        git_tree: "1".repeat(40),
                        repository_tree_sha256: [2; 32],
                        package_path: String::new(),
                        logical_root: fixture.0.join(".lorry/git/demo/source"),
                        physical_root: fixture.0.join("object/source"),
                        source_tree_sha256: [3; 32],
                        patched_crates_io: true,
                    },
                ),
            ],
        };

        let rendered =
            String::from_utf8(render_workspace(&resolution, Format::V4).unwrap()).unwrap();
        assert!(rendered.contains(&format!("source = \"{cargo_source}\"")));
        assert!(!rendered.contains("checksum ="));
        assert!(rendered.contains("dependencies = [\n \"demo\",\n]"));
    }

    #[test]
    fn renders_cargo_v4_path_and_registry_disambiguation_and_round_trips() {
        let fixture = Fixture::new();
        let registry_key = PackageKey {
            name: "cfg-if".to_owned(),
            version: Version::parse("1.0.4").unwrap(),
            source: PackageSourceKey::CratesIo,
        };
        let local = path_package("cfg-if", "1.0.4", &fixture.0.join("local"));
        let mut root = path_package("lock-oracle", "0.1.0", &fixture.0);
        root.lock_edges = vec![
            lock_edge(registry_key.clone()),
            lock_edge(local.key.clone()),
        ];
        let resolution = Resolution {
            root_edges: Vec::new(),
            packages: vec![
                local,
                package(registry_key, ResolvedSource::CratesIo { checksum: [9; 32] }),
                root,
            ],
        };
        let rendered = render_workspace(&resolution, Format::V4).unwrap();
        let expected = format!(
            concat!(
                "# This file is automatically @generated by Cargo.\n",
                "# It is not intended for manual editing.\n",
                "version = 4\n\n",
                "[[package]]\n",
                "name = \"cfg-if\"\n",
                "version = \"1.0.4\"\n\n",
                "[[package]]\n",
                "name = \"cfg-if\"\n",
                "version = \"1.0.4\"\n",
                "source = \"{}\"\n",
                "checksum = \"{}\"\n\n",
                "[[package]]\n",
                "name = \"lock-oracle\"\n",
                "version = \"0.1.0\"\n",
                "dependencies = [\n",
                " \"cfg-if 1.0.4\",\n",
                " \"cfg-if 1.0.4 ({})\",\n",
                "]\n",
            ),
            CRATES_IO_SOURCE,
            hex(&[9; 32]),
            CRATES_IO_SOURCE,
        );
        assert_eq!(rendered, expected.as_bytes());

        fs::write(fixture.0.join("Cargo.lock"), &rendered).unwrap();
        let loaded = crate::manifest::Lockfile::load(&fixture.0.join("Cargo.lock")).unwrap();
        crate::offline::validate_workspace_resolution(&loaded, &resolution).unwrap();
    }
