use super::{Registry, messages};
use serde_json::json;
use std::fs;

pub fn run() {
    let r = Registry::new();
    let p = &r.project;
    let files = [("src/lib.rs", "pub fn value() {}\n")];
    let first = r.versioned_package("leaf", "1.0.0", "", &files, json!([]));
    let second = r.versioned_package("leaf", "1.1.0", "", &files, json!([]));
    p.write("Cargo.toml", "[workspace]\nmembers=[\"app\",\"shared\"]\nexclude=[\"outside\",\"patched\"]\ndefault-members=[\"app\"]\nresolver=\"2\"\n");
    p.package(
        "app",
        "app",
        "[dependencies]\nshared={path=\"../shared\"}\n",
    );
    p.package(
        "shared",
        "shared",
        "[dependencies]\noutside={path=\"../outside\"}\n",
    );
    p.package("outside", "outside", "[dependencies]\nleaf=\"1.0\"\n");
    for member in ["app", "shared", "outside"] {
        p.write(&format!("{member}/src/lib.rs"), "pub fn value() {}\n");
    }
    let before = format!(
        "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"app\"\nversion = \"1.0.0\"\ndependencies = [\n \"shared\",\n]\n\n[[package]]\nname = \"leaf\"\nversion = \"1.0.0\"\nsource = \"registry+https://github.com/rust-lang/crates.io-index\"\nchecksum = \"{first}\"\n\n[[package]]\nname = \"outside\"\nversion = \"1.0.0\"\ndependencies = [\n \"leaf\",\n]\n\n[[package]]\nname = \"shared\"\nversion = \"1.0.0\"\ndependencies = [\n \"outside\",\n]\n"
    );
    p.write("Cargo.lock", &before);
    p.success(&["-q", "--lorry-messages", "vendor", "--accept-all"]);
    assert_eq!(
        fs::read_to_string(p.root.join("Cargo.lock")).unwrap(),
        before
    );
    let users = p.success(&[
        "-q",
        "vendor",
        "--locked",
        "--offline",
        "--all-features",
        "--accept-all",
    ]);
    let text = String::from_utf8_lossy(&users.stderr);
    assert_eq!(text.matches("Package: leaf ").count(), 1);
    assert!(text.contains("member users: app, shared"), "{text}");
    let output = p.success(&[
        "-q",
        "--lorry-messages",
        "vendor",
        "--accept-all",
        "upgrade",
        "leaf",
        "--to",
        "1.1.0",
    ]);
    let events = messages(&output);
    assert_eq!(events.len(), 1);
    assert_eq!(events[0]["added"][0]["name"], "leaf");
    assert_eq!(events[0]["added"][0]["version"], "1.1.0");
    assert_eq!(events[0]["removed"][0]["version"], "1.0.0");
    let upgraded = fs::read_to_string(p.root.join("Cargo.lock")).unwrap();
    assert_eq!(
        upgraded,
        before
            .replace(
                "name = \"leaf\"\nversion = \"1.0.0\"",
                "name = \"leaf\"\nversion = \"1.1.0\""
            )
            .replace(&first, &second)
    );
    let admission = fs::read(p.root.join(".lorry/dependencies-v2.toml")).unwrap();
    p.package(
        "shared",
        "shared",
        "[dependencies]\noutside={path=\"../outside\"}\nleaf={version=\"1.0\",optional=true}\n",
    );
    p.fails(
        &[
            "-q",
            "--lorry-messages",
            "vendor",
            "--accept-all",
            "upgrade",
            "leaf",
            "--to",
            "1.1.0",
        ],
        "direct dependency",
    );
    assert_eq!(
        fs::read_to_string(p.root.join("Cargo.lock")).unwrap(),
        upgraded
    );
    assert_eq!(
        fs::read(p.root.join(".lorry/dependencies-v2.toml")).unwrap(),
        admission
    );
    // A source-only metadata command accepts unsupported compiler outputs.
    p.write("patched/Cargo.toml", "[package]\nname=\"leaf\"\nversion=\"1.1.0\"\nedition=\"2024\"\n[lib]\ncrate-type=[\"staticlib\"]\n");
    p.write(
        "patched/src/lib.rs",
        "compile_error!(\"metadata must not compile patched sources\");\n",
    );
    let manifest = fs::read_to_string(p.root.join("Cargo.toml")).unwrap();
    p.write(
        "Cargo.toml",
        format!("{manifest}\n[patch.crates-io]\nleaf={{path=\"patched\"}}\n"),
    );
    p.success(&["vendor", "--accept-all"]);
    let lock = fs::read(p.root.join("Cargo.lock")).unwrap();
    let output = p.success(&["metadata", "--offline", "--locked", "--format-version", "1"]);
    let metadata: serde_json::Value = serde_json::from_slice(&output.stdout).unwrap();
    let package = metadata["packages"]
        .as_array()
        .unwrap()
        .iter()
        .find(|p| p["name"] == "leaf")
        .unwrap();
    assert!(package["source"].is_null());
    assert_eq!(
        package["manifest_path"],
        p.root.join("patched/Cargo.toml").to_str().unwrap()
    );
    assert_eq!(package["targets"][0]["crate_types"], json!(["staticlib"]));
    assert_eq!(fs::read(p.root.join("Cargo.lock")).unwrap(), lock);
    println!(
        "PASS: transitive upgrades protect member declarations and path patches retain source metadata"
    );
}
