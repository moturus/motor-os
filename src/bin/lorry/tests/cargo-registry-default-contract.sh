#!/usr/bin/env bash
# By default Lorry builds from Cargo's cache like Cargo: no admission, allow
# rules, or capability grants. Deny rules still apply. Turning the mode off,
# or a cache that lacks a package, gives Lorry repositories and admission.
set -euo pipefail
export CARGO_NET_OFFLINE=true

if [ "$#" -ne 1 ]; then
    echo "usage: cargo-registry-default-contract.sh LORRY" >&2
    exit 2
fi
LORRY="$(realpath "$1")"
SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
if [ -z "${LORRY_TEST_RUSTC:-}" ]; then
    # shellcheck source=current-toolchain.sh
    source "$SCRIPT_DIR/current-toolchain.sh"
    lorry_load_current_toolchain
fi
WORK="$(mktemp -d "${TMPDIR:-/tmp}/lorry-cargo-registry-default.XXXXXX")"
trap 'rm -rf -- "$WORK"' EXIT
fail() {
    echo "FAIL: $*" >&2
    exit 1
}

CACHE="$WORK/cargo-home"
APP="$WORK/app"
mkdir -p "$WORK/home/.config/lorry" "$APP/src"
printf 'config-version = 1\n[cache]\ndirectory = "%s"\n' "$WORK/cache" \
    >"$WORK/home/.config/lorry/lorry.toml"

# Two crates in Cargo's cache layout: one with a build script, one procedural
# macro. Prints the lockfile entries with each archive's checksum.
python3 -I - "$CACHE" >"$WORK/locked.toml" <<'PYEOF'
import hashlib, io, os, sys, tarfile

home = sys.argv[1]
registry = "index.crates.io-fixture"
crates = {
    ("scripted", "1.0.0"): {
        "Cargo.toml": '[package]\nname = "scripted"\nversion = "1.0.0"\nedition = "2021"\nlicense = "MIT"\nbuild = "build.rs"\n',
        "build.rs": 'fn main() {\n    println!("cargo:rustc-env=SCRIPTED=from-build-script");\n}\n',
        "src/lib.rs": 'pub const VALUE: &str = env!("SCRIPTED");\n',
    },
    ("derive-answer", "1.0.0"): {
        "Cargo.toml": '[package]\nname = "derive-answer"\nversion = "1.0.0"\nedition = "2021"\nlicense = "MIT"\n\n[lib]\nproc-macro = true\n',
        "src/lib.rs": 'extern crate proc_macro;\nuse proc_macro::TokenStream;\n\n#[proc_macro]\npub fn answer(_: TokenStream) -> TokenStream {\n    "42".parse().unwrap()\n}\n',
    },
}
for (name, version), files in crates.items():
    leaf = f"{name}-{version}"
    source = os.path.join(home, "registry/src", registry, leaf)
    cache = os.path.join(home, "registry/cache", registry)
    os.makedirs(cache, exist_ok=True)
    archive = io.BytesIO()
    with tarfile.open(fileobj=archive, mode="w:gz", format=tarfile.USTAR_FORMAT) as tar:
        for path, text in files.items():
            data = text.encode()
            target = os.path.join(source, path)
            os.makedirs(os.path.dirname(target), exist_ok=True)
            with open(target, "wb") as output:
                output.write(data)
            info = tarfile.TarInfo(f"{leaf}/{path}")
            info.size = len(data)
            info.mode = 0o644
            tar.addfile(info, io.BytesIO(data))
    with open(os.path.join(source, ".cargo-ok"), "w") as marker:
        marker.write('{"v":1}')
    with open(os.path.join(cache, f"{leaf}.crate"), "wb") as output:
        output.write(archive.getvalue())
    checksum = hashlib.sha256(archive.getvalue()).hexdigest()
    print(f'\n[[package]]\nname = "{name}"\nversion = "{version}"\n'
          f'source = "registry+https://github.com/rust-lang/crates.io-index"\n'
          f'checksum = "{checksum}"')
PYEOF

cat >"$APP/Cargo.toml" <<'EOF'
[package]
name = "app"
version = "0.1.0"
edition = "2021"

[dependencies]
derive-answer = "1"
scripted = "1"
EOF
cat >"$APP/build.rs" <<'EOF'
fn main() {
    println!("cargo:rustc-env=MEMBER=member-script");
}
EOF
cat >"$APP/src/main.rs" <<'EOF'
fn main() {
    println!("{} {} {}", scripted::VALUE, derive_answer::answer!(), env!("MEMBER"));
}
EOF
{
    printf '# This file is automatically @generated by Cargo.\n'
    printf '# It is not intended for manual editing.\nversion = 4\n\n'
    printf '[[package]]\nname = "app"\nversion = "0.1.0"\n'
    printf 'dependencies = [\n "derive-answer",\n "scripted",\n]\n'
    cat "$WORK/locked.toml"
} >"$APP/Cargo.lock"

lorry() {
    (cd "$APP" && HOME="$WORK/home" CARGO_HOME="$CACHE" RUSTC="$LORRY_TEST_RUSTC" \
        "$LORRY" "$@")
}
expect_failure() {
    local name=$1 pattern=$2
    shift 2
    if lorry "$@" >"$WORK/$name.out" 2>"$WORK/$name.err"; then
        fail "$name unexpectedly succeeded"
    fi
    grep -E "$pattern" "$WORK/$name.err" >/dev/null ||
        fail "$name did not report /$pattern/: $(cat "$WORK/$name.err")"
}

# Default mode: the build scripts and the procedural macro run without any
# admission state or policy rules.
output="$(lorry run --quiet)"
[ "$output" = "from-build-script 42 member-script" ] ||
    fail "default build printed: $output"
[ ! -e "$APP/.lorry" ] || fail "the default mode wrote admission state"
lorry build --quiet
lorry build -v >"$WORK/again.out" 2>"$WORK/again.err"
grep -F "accepted fresh root profile before dependency admission" "$WORK/again.err" >/dev/null ||
    fail "an unchanged build did not reuse its completed profile"
lorry metadata --format-version 1 >"$WORK/metadata.json"
python3 -I - "$WORK/metadata.json" <<'PYEOF'
import json, sys
names = {package["name"] for package in json.load(open(sys.argv[1]))["packages"]}
assert names == {"app", "derive-answer", "scripted"}, names
PYEOF

# Explicit deny rules still apply.
printf 'config-version = 1\n[policy.rules.no-scripted]\naction = "deny"\nname = "scripted"\n' \
    >"$APP/lorry.toml"
expect_failure deny 'no-scripted' build
rm "$APP/lorry.toml"

# Turned off on the command line or in configuration, Lorry needs its own
# repositories and admission.
lorry_mode='workspace admission|Lorry repositories'
expect_failure flag-off "$lorry_mode" --no-use-cargo-registry build
printf 'config-version = 1\nuse-cargo-registry = false\n' >"$APP/lorry.toml"
expect_failure config-off "$lorry_mode" build
rm "$APP/lorry.toml"

# A package missing from Cargo's cache sends the default mode to Lorry
# repositories; the explicit option reports the missing package instead. The
# edit keeps the unchanged-build record, which reads no sources, out of play.
printf '// edited\n' >>"$APP/src/main.rs"
mv "$CACHE/registry/src/index.crates.io-fixture/derive-answer-1.0.0" "$WORK/moved"
expect_failure fallback "$lorry_mode" -v build
grep -F "Using Lorry repositories because Cargo's cache cannot be used" "$WORK/fallback.err" \
    >/dev/null || fail "the fallback did not explain itself in verbose mode"
for note in '^Verifying dependency state$' '^Using .*rustc'; do
    [ "$(grep -c "$note" "$WORK/fallback.err")" -eq 1 ] ||
        fail "the fallback repeated /$note/: $(cat "$WORK/fallback.err")"
done
expect_failure explicit 'does not contain both the archive and extracted source' \
    --use-cargo-registry build
mv "$WORK/moved" "$CACHE/registry/src/index.crates.io-fixture/derive-answer-1.0.0"

# Without a Cargo cache the default is Lorry repositories.
(cd "$APP" && HOME="$WORK/home" CARGO_HOME="$WORK/absent" RUSTC="$LORRY_TEST_RUSTC" \
    "$LORRY" build) >"$WORK/absent.out" 2>"$WORK/absent.err" &&
    fail "a build without a Cargo cache unexpectedly succeeded"
grep -E "$lorry_mode" "$WORK/absent.err" >/dev/null ||
    fail "a build without a Cargo cache did not use Lorry repositories: $(cat "$WORK/absent.err")"

echo "PASS: Lorry builds from Cargo's cache by default and falls back to its repositories"
